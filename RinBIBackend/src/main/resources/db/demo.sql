CREATE TABLE IF NOT EXISTS customer (
    id BIGINT PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    region VARCHAR(32) NOT NULL,
    level VARCHAR(20),
    register_date DATE
);

-- 字段注释会作为最终回答中的列名，避免向用户暴露真实字段名
COMMENT ON TABLE customer IS '客户';
COMMENT ON COLUMN customer.id IS '客户编号';
COMMENT ON COLUMN customer.customer_name IS '客户名称';
COMMENT ON COLUMN customer.region IS '所属地区';
COMMENT ON COLUMN customer.level IS '客户等级';
COMMENT ON COLUMN customer.register_date IS '注册日期';

CREATE TABLE IF NOT EXISTS product (
    id BIGINT PRIMARY KEY,
    product_name VARCHAR(100) NOT NULL,
    category VARCHAR(32) NOT NULL,
    list_price DECIMAL(12, 2) NOT NULL,
    stock INT NOT NULL
);

COMMENT ON TABLE product IS '商品';
COMMENT ON COLUMN product.id IS '商品编号';
COMMENT ON COLUMN product.product_name IS '商品名称';
COMMENT ON COLUMN product.category IS '商品分类';
COMMENT ON COLUMN product.list_price IS '商品标价';
COMMENT ON COLUMN product.stock IS '库存数量';

CREATE TABLE IF NOT EXISTS sales_order (
    id BIGINT PRIMARY KEY,
    order_no VARCHAR(32) NOT NULL,
    customer_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INT NOT NULL,
    unit_price DECIMAL(12, 2) NOT NULL,
    amount DECIMAL(14, 2) NOT NULL,
    order_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL
);

COMMENT ON TABLE sales_order IS '销售订单';
COMMENT ON COLUMN sales_order.id IS '订单编号';
COMMENT ON COLUMN sales_order.order_no IS '订单号';
COMMENT ON COLUMN sales_order.customer_id IS '客户编号';
COMMENT ON COLUMN sales_order.product_id IS '商品编号';
COMMENT ON COLUMN sales_order.quantity IS '购买数量';
COMMENT ON COLUMN sales_order.unit_price IS '成交单价';
COMMENT ON COLUMN sales_order.amount IS '订单金额';
COMMENT ON COLUMN sales_order.order_date IS '下单日期';
COMMENT ON COLUMN sales_order.status IS '订单状态';

